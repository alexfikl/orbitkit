# {{{ generator


class Generator(ABC):
    @abstractmethod
    def integers(
        self,
        low: int,
        high: int | None = None,
        size: ShapeT | None = None,
        *,
        dtype: DTypeLike | None = None,
    ) -> Array[np.integer[Any], ShapeT]:
        pass

    @abstractmethod
    def random(
        self,
        size: ShapeT | None = None,
        *,
        dtype: DTypeLike | None = None,
    ) -> Array[ShapeT, np.floating[Any]]:
        pass

    @abstractmethod
    def choice(
        self,
        a: int | ArrayND[ScalarTypeT],
        size: ShapeT | None = None,
        *,
        replace: bool = True,
    ) -> Array[ShapeT, ScalarTypeT]:
        pass


